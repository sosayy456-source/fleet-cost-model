/* ---------- หาเส้นทางสั้นที่สุด (Dijkstra) ---------- */
const coord = {
  ...Object.fromEntries(CORRIDOR.map((c, i) => ["C" + i, c])),
  ...ROAD_NODES,
  ...Object.fromEntries(Object.entries(STOPS).map(([n, s]) => [n, s.c]))
};
const dist = (a, b) => {
  const kx = Math.cos((a[1] + b[1]) / 2 * Math.PI / 180);
  return Math.hypot((a[0] - b[0]) * kx, a[1] - b[1]);
};
const adj = {};
ROAD_EDGES.forEach(([a, b]) => {
  if (!coord[a] || !coord[b]) throw new Error(`roads.js: ไม่รู้จักโหนด ${coord[a] ? b : a}`);
  const w = dist(coord[a], coord[b]);
  (adj[a] ||= []).push([b, w]);
  (adj[b] ||= []).push([a, w]);
});

const cache = new Map();
/** พิกัด [lon, lat] ตามแนวถนนจากจุด from ไปจุด to (ต่อเส้นตรงถ้าหาทางไม่เจอ) */
export function roadPath(from, to) {
  const key = from + "→" + to;
  if (cache.has(key)) return cache.get(key);
  const d = { [from]: 0 }, prev = {}, done = new Set();
  while (true) {
    let u = null;
    for (const n in d) if (!done.has(n) && (u === null || d[n] < d[u])) u = n;
    if (u === null || u === to) break;
    done.add(u);
    for (const [v, w] of adj[u] || []) {
      if (d[v] === undefined || d[u] + w < d[v]) { d[v] = d[u] + w; prev[v] = u; }
    }
  }
  const ids = [to];
  while (prev[ids[0]] !== undefined) ids.unshift(prev[ids[0]]);
  const out = ids[0] === from ? ids.map(n => coord[n]) : [coord[from], coord[to]];
  cache.set(key, out);
  return out;
}
