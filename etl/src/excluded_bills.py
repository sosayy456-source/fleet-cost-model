EXCLUDED_BILLS: dict[str, str] = {
    # 28 ก.ย. 2569 — อาหารเจสด 1 กล่อง 145 บาท (ใบรายการ 5240652680051 · 10/06/2567) ช่อง "น้ำหนักต่อหน่วย"
    # เป็นเลข 15 หลัก 112,756,035,249,154 น้ำหนักรวม 0 → ETL นับ จำนวน × น้ำหนักต่อหน่วย เป็นแสนล้านตัน
    # ตัน-กม. ของรถทั้งปีพอง บาท/ตัน-กม. ปีก่อนเหลือเกือบ 0 · % เปลี่ยนแปลงของรถ 10 ล้อช่วงยาวขึ้นหลักล้าน %
    "5224060112113": "น้ำหนักต่อหน่วยกรอกผิดเป็นเลข 15 หลัก",
}


def bill_key(v: object) -> str:
    """เลขที่บิลเป็นสตริงสำหรับเทียบ — ตัดช่องว่างและ .0 ท้ายเลข"""
    s = "" if v is None else str(v).strip()
    return s[:-2] if s.endswith(".0") else s


def is_excluded(bill: object) -> bool:
    return bill_key(bill) in EXCLUDED_BILLS
