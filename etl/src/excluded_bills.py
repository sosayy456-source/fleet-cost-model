"""
บิลที่ ETL ข้ามทิ้งทุกครั้งที่อ่านไฟล์รายได้ — ข้อมูลในไฟล์ต้นทางผิดจนใช้ไม่ได้
สองแบบ: เลขที่บิลในรายการ EXCLUDED_BILLS (เจ้าของงานสั่งตัดทีละใบ) · น้ำหนักบิลเกิน ABSURD_KG (ตัดอัตโนมัติ · is_absurd_weight)

ใช้ทุกที่ที่อ่านแถวบิลจากไฟล์รายได้: build_costrev.py (ต้นทุน+รายได้รายเที่ยว · น้ำหนัก wt) ·
build_alloc.py (item_reader — ปันส่วนทั้งสามรอบ) · src/loaders/revenue.py (build_json.py)
เทียบเลขที่บิลเป็นสตริง ตัด ".0" ที่ calamine/pandas ใส่มาให้ก่อน (เลข 13 หลักอ่านเป็น float)

เพิ่มบิลใหม่: ใส่เลขที่บิล + เหตุผล แล้วรัน ETL ใหม่ (plugin เฝ้าแค่ .xlsx ไม่รู้ว่าไฟล์นี้เปลี่ยน)
"""

EXCLUDED_BILLS: dict[str, str] = {
    # 28 ก.ย. 2569 — อาหารเจสด 1 กล่อง 145 บาท (ใบรายการ 5240652680051 · 10/06/2567) ช่อง "น้ำหนักต่อหน่วย"
    # เป็นเลข 15 หลัก 112,756,035,249,154 น้ำหนักรวม 0 → ETL นับ จำนวน × น้ำหนักต่อหน่วย เป็นแสนล้านตัน
    # ตัน-กม. ของรถทั้งปีพอง บาท/ตัน-กม. ปีก่อนเหลือเกือบ 0 · % เปลี่ยนแปลงของรถ 10 ล้อช่วงยาวขึ้นหลักล้าน %
    "5224060112113": "น้ำหนักต่อหน่วยกรอกผิดเป็นเลข 15 หลัก",
}


#: บิลเดียวหนักเกินเท่านี้ (กก.) = ข้อมูลผิดแน่ ตัดทิ้งอัตโนมัติ (เจ้าของงานสั่ง 28 ก.ย. 2569 "น้ำหนักเกินเป็นล้าน ๆ ให้กรองออก")
#: ไม่มีรถคันไหนบรรทุกได้ถึงพันตัน · ต่ำกว่านี้ (เช่นกรอกเป็นกรัมจนได้หลักสิบ–ร้อยตัน) ยังนับตามเดิม
ABSURD_KG = 1_000_000

#: รุ่นของกติกาตัดทิ้ง — เปลี่ยนกติกา (เกณฑ์/วิธีคิด) แล้วต้องเพิ่มเลข plugin autoEtl จะเห็นว่าผลลัพธ์เก่าไม่ตรงแล้วแปลงใหม่เอง
#: ★ plugin อ่านเลขนี้ด้วย regex บรรทัด `RULES_VERSION = <เลข>`
RULES_VERSION = 2


def weight_kg(qty: float, unit_kg: float, total_kg: float) -> float:
    """น้ำหนักของบิลหนึ่งแถว (กก.) กติกาเดียวกับ build_costrev.line_weight_kg: น้ำหนักรวม > 0 ใช้ค่านั้น ไม่งั้น จำนวน × น้ำหนักต่อหน่วย"""
    if total_kg > 0:
        return total_kg
    return qty * unit_kg if qty > 0 and unit_kg > 0 else 0.0


def is_absurd_weight(qty: float, unit_kg: float, total_kg: float) -> bool:
    """น้ำหนักของบิลเกิน ABSURD_KG — เช่น ช่องน้ำหนักต่อหน่วยมีเลข 15 หลัก (บิล 5224060112113 · 112 ล้านล้าน กก.)"""
    return weight_kg(qty, unit_kg, total_kg) > ABSURD_KG


def excluded_list() -> list[str]:
    """รายการเลขที่บิลที่ตัดทิ้ง (เรียงแล้ว) — ETL เขียนลง manifest.excludedBills ของชุด costrev/alloc
    plugin autoEtl (app/vite.config.ts) เทียบกับเลขในไฟล์นี้ตอนเปิด dev และทุก 2 วินาที ไม่ตรง = รัน ETL ใหม่เอง
    (เจ้าของงานสั่ง 28 ก.ย. 2569 — เพื่อน merge แล้วบิลต้องถูกตัดโดยไม่ต้องสั่ง ETL เอง)
    ★ plugin อ่านเลขจากไฟล์นี้ด้วย regex บรรทัด `"<ตัวเลข>": ...` — คีย์ต้องเป็นเลขล้วนในเครื่องหมายคำพูดคู่ บรรทัดละคีย์"""
    return sorted(EXCLUDED_BILLS)


def bill_key(v: object) -> str:
    """เลขที่บิลเป็นสตริงสำหรับเทียบ — ตัดช่องว่างและ .0 ท้ายเลข"""
    s = "" if v is None else str(v).strip()
    return s[:-2] if s.endswith(".0") else s


def is_excluded(bill: object) -> bool:
    return bill_key(bill) in EXCLUDED_BILLS
